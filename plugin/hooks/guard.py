"""Guards for the dotagent: commit style, PR title, no plan labels in names, the workflow mode, read-only planning.

Reads one hook event as JSON on stdin. Exit 2 with a reason on stderr blocks the tool call, a rule that needs a
human yes returns `ask` so Claude Code shows its own prompt, and everything else passes. Only the rules that
can never be right (a trailer, a force push, a protected path) block outright. Settings live in one file,
.dotagent/config.json in the project. Edit it by hand or run `sh run.sh set <key> <value>` (the /dotagent:workflow command does).
"""
import json
import os
import re
import shlex
import subprocess
import sys
import time

EM_DASH = chr(0x2014)
EMOJI = re.compile("[" + chr(0x1F300) + "-" + chr(0x1FAFF) + chr(0x2600) + "-" + chr(0x27BF) + chr(0x1F000) + "-" + chr(0x1F2FF) + "]")
TYPES = "feat|fix|hotfix|docs|style|refactor|test|chore|perf|revert|ci|build"
SCOPE = r"\([a-zA-Z0-9_.-]+\)"
TYPE_LIST = re.compile(r"[a-z]+(,[a-z]+)*")
BRANCH = re.compile(r"[A-Za-z0-9._/-]+")
MERGE_SUBJECT = re.compile(r"\(#(\d+)\)$")
COMMIT_LINE = re.compile(r"^- [0-9a-f]{7,40} \S")  # one line per commit in a squash body: `- 1a2b3c4 feat(auth): add login`
# GitHub adds the PR number on merge, so a commit or PR title never writes it: only the merge subject ends with it.
PR_NUMBER = re.compile(r"\(#\d+\)")
# A name says what changed, never where it sits in the plan: no "milestone-1", "task 2", "slice-3", "finishing task", "(wip)".
LABEL = re.compile(
    r"\bmilestone[-_ #]*\d+\b|\b(task|slice|step|phase|sprint)[-_ #]*\d+\b"
    r"|\b(finish(ed|ing)?|complete[d]?|done with)\s+(the\s+)?(task|slice|step|phase|milestone)\b|\((milestone|task|todo|wip)\)|\bwip\b",
    re.I,
)
# A commit or PR carries no tool trailer: no Co-Authored-By, no "Generated with ...", no robot emoji.
TRAILER = re.compile(r"co-authored-by|signed-off-by|generated with|generated by (claude|ai|an ai|copilot|chatgpt|codex)|claude\.com/claude-code|" + chr(0x1F916), re.I)
# A shell command that changes files: a redirect (not 2> or >&), sed -i, tee, cp, mv, rm, touch, or a git command that rewrites the tree.
WRITE = re.compile(
    r"(?<![0-9])>(?!&)|\bsed\s+-[a-zA-Z]*i|\btee\b|\b(cp|mv|rm|touch|truncate|mkdir)\s"
    r"|\bgit\s+((apply|restore|reset|stash|add|rm|clean|am|cherry-pick|merge|rebase)\b|checkout\s+--)"
)
TODO = os.path.join("docs", "TODO.md")
RUNS = os.path.join(".dotagent", "runs.jsonl")  # one JSON line per event: a subagent spawn, a gate pass, a plan phase
PHASE_TTL = 3600  # a forgotten plan phase must never lock a repo for long
PHASE_TTL = 3600  # a forgotten plan phase must never lock a repo for long


# Allowed values per setting, the first one is the default. A missing or invalid value falls back to it.
# The workflow modes were autopilot, checkpoint, and adapt before 0.4.0. The old names still work and are saved under the new one.
MODE_ALIASES = {"autopilot": "auto", "checkpoint": "ask", "adapt": "local"}
CHOICES = {
    "workflow": ("auto", "ask", "local"),
    "merge_method": ("squash", "merge", "rebase"),  # how a PR merges, squash unless the repo only allows another
    "commit_scope": ("required", "optional"),  # whether `type(scope): summary` needs its scope
    "em_dash": ("block", "allow"),
    "emoji": ("block", "allow"),
}
# Answers the user gave once, so a skill never asks twice. Unset means not asked yet.
ANSWERS = {
    "setup": ("full", "minimal", "skipped"),  # how much setup the user chose
    "hooks": ("on", "declined"),  # the answer about git hooks
    "big_plan": ("ok",),  # the user agreed to a plan of more than 6 PRs
    "agents": ("claude", "codex", "both", "other"),  # the AI agent the user runs dotagent with, from the setup interview
}
CONFIG = os.path.join(".dotagent", "config.json")
_settings = None
CLIENT = "claude"  # "codex" when the Codex hook entry runs it with --client codex, see hooks/hooks.json at the repo root


def project_dir():
    return os.environ.get("CLAUDE_PROJECT_DIR") or os.getcwd()


def config_path(base=None):
    return os.path.join(base or project_dir(), CONFIG)


def is_path(path, rel):
    norm = os.path.normpath(path)
    return norm == rel or norm.endswith(os.sep + rel)


def entries():
    # Every event in runs.jsonl, oldest first. A line that is not a JSON object is skipped.
    try:
        with open(os.path.join(project_dir(), RUNS), encoding="utf-8") as handle:
            lines = handle.readlines()
    except OSError:
        return []
    found = []
    for line in lines:
        try:
            event = json.loads(line)
        except ValueError:
            continue
        if isinstance(event, dict):
            found.append(event)
    return found


def last(key):
    # The newest event that has the key, or None.
    for event in reversed(entries()):
        if key in event:
            return event
    return None


def record(**fields):
    # Appends one event with its time. runs.jsonl is the only state file besides config.json.
    path = os.path.join(project_dir(), RUNS)
    try:
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, "a", encoding="utf-8", newline="\n") as handle:
            handle.write(json.dumps({"t": int(time.time()), **fields}) + "\n")
    except OSError:
        return
    ensure_ignored()


def phase():
    # "plan" while the run only reads and writes the TODO, empty when done, stale, or never set.
    found = last("phase")
    if not found or found["phase"] == "done" or time.time() - found.get("t", 0) >= PHASE_TTL:
        return ""
    return found["phase"]


def load(base=None):
    # Reads the config file once. No file or no key means the default. A key that is there but wrong, or a broken
    # file, means the strictest value (merge off), so a typo never turns merging on.
    path = config_path(base)
    try:
        with open(path, encoding="utf-8") as handle:
            raw = json.load(handle)
        broken = not isinstance(raw, dict)
    except OSError:
        raw, broken = {}, False
    except ValueError:
        raw, broken = {}, True
    raw = raw if isinstance(raw, dict) else {}
    values = {}
    for key, allowed in CHOICES.items():
        if key in raw and raw[key] in allowed:
            values[key] = raw[key]
        elif key == "workflow":
            values[key] = workflow_mode(raw, broken)
        else:
            values[key] = allowed[0]
    skills = raw.get("style_skills")
    values["style_skills"] = skills if isinstance(skills, str) and skills else "none"
    protected = raw.get("protected")
    values["protected"] = protected if isinstance(protected, str) else ""
    # A repo flow that is not the default: its own commit types and its base branch. Empty means the default.
    types = raw.get("commit_types")
    values["commit_types"] = types if isinstance(types, str) and TYPE_LIST.fullmatch(types) else ""
    base = raw.get("base_branch")
    values["base_branch"] = base if isinstance(base, str) and BRANCH.fullmatch(base) else ""
    for key, allowed in ANSWERS.items():
        values[key] = raw[key] if raw.get(key) in allowed else ""
    return values


def workflow_mode(raw, broken):
    # auto pushes and merges by itself, ask stops for your yes before anything leaves the machine, local never pushes.
    # A wrong value or a broken file means local, the mode that sends nothing, so a typo never turns pushing on.
    # The old `merge` key is read once: on-green and full were auto, off stopped before the merge (ask).
    if broken:
        return "local"
    if "workflow" in raw:
        mode = MODE_ALIASES.get(raw["workflow"], raw["workflow"])
        return mode if mode in CHOICES["workflow"] else "local"
    if "merge" in raw:
        return {"on-green": "auto", "full": "auto", "off": "ask"}.get(raw["merge"], "local")
    return "auto"


def raw_config():
    # The keys in the config file as written, {} when there is no file or it is broken.
    try:
        with open(config_path(), encoding="utf-8") as handle:
            raw = json.load(handle)
        return raw if isinstance(raw, dict) else {}
    except (OSError, ValueError):
        return {}


def is_first_run():
    # A repo that never saved the workflow or the setup answer has not met dotagent yet. `scale` and `merge` are old keys,
    # still read so a config saved before they went away does not look new.
    return not {"setup", "scale", "merge", "workflow"} & set(raw_config())


def is_config(path):
    # Only this project's config, not a copy of one in a subfolder such as examples/.
    return os.path.abspath(path) == os.path.abspath(config_path())


def ensure_ignored():
    # The config and the markers are per machine. Git ignores them through .git/info/exclude, which is never pushed,
    # so no tracked file changes. Skipped when the repo already ignores them or this is not a git repo.
    try:
        base = ["git", "-C", project_dir()]
        if subprocess.run(base + ["check-ignore", "-q", ".dotagent/config.json"], capture_output=True, timeout=5).returncode == 0:
            return
        out = subprocess.run(base + ["rev-parse", "--git-path", "info/exclude"], capture_output=True, text=True, timeout=5).stdout.strip()
    except (OSError, subprocess.SubprocessError):
        return
    if not out:
        return
    path = out if os.path.isabs(out) else os.path.join(project_dir(), out)
    try:
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, "a", encoding="utf-8", newline="\n") as handle:
            handle.write(".dotagent/\n")
    except OSError:
        pass


def git_hooks():
    # "none" when the repo has no .githooks folder, else "on" when git uses it and "off" when it does not. The git hooks
    # check every commit and push, by the agent, a person, or a script, so a repo that ships them but has them off is exposed.
    if not os.path.isdir(os.path.join(project_dir(), ".githooks")):
        return "none"
    try:
        found = subprocess.run(
            ["git", "-C", project_dir(), "config", "--get", "core.hooksPath"], capture_output=True, text=True, timeout=5
        ).stdout.strip()
    except (OSError, subprocess.SubprocessError):
        return "none"
    return "on" if found.replace("\\", "/").rstrip("/").endswith(".githooks") else "off"


def clean_head():
    # The HEAD sha when no tracked file differs from it, else "". Empty also outside a git repo.
    base = ["git", "-C", project_dir()]
    try:
        head = subprocess.run(base + ["rev-parse", "HEAD"], capture_output=True, text=True, timeout=5)
        dirty = subprocess.run(base + ["status", "--porcelain", "--untracked-files=no"], capture_output=True, text=True, timeout=5)
    except (OSError, subprocess.SubprocessError):
        return ""
    return head.stdout.strip() if head.returncode == 0 and dirty.returncode == 0 and not dirty.stdout.strip() else ""


def gate_check():
    # "ok" when the gate passed at this exact commit and nothing tracked changed since, else "stale". Bookkeeping the
    # agent trusts, CI is the real check.
    head = clean_head()
    found = last("gate")
    return "ok" if head and found and found.get("gate") == head else "stale"


def todo_prs():
    # The PRs in docs/TODO.md that still have an unticked subtask or no done: line, as (title, body).
    try:
        with open(os.path.join(project_dir(), TODO), encoding="utf-8") as handle:
            text = handle.read()
    except OSError:
        return []
    left = []
    for found in re.finditer(r"(?ms)^## PR \d+:\s*(.+?)\n(.*?)(?=^## |\Z)", text):
        if "- [ ]" in found.group(2) or not re.search(r"(?m)^done:[ \t]*\S", found.group(2)):
            left.append((found.group(1).strip(), found.group(2)))
    return left


def unfinished():
    return [title for title, _ in todo_prs()]


def glob_re(pattern):
    # `**` crosses folders, `*` and `?` stay inside one.
    out, i = "", 0
    while i < len(pattern):
        if pattern.startswith("**/", i):
            out, i = out + "(?:.*/)?", i + 3
        elif pattern.startswith("**", i):
            out, i = out + ".*", i + 2
        elif pattern[i] == "*":
            out, i = out + "[^/]*", i + 1
        elif pattern[i] == "?":
            out, i = out + "[^/]", i + 1
        else:
            out, i = out + re.escape(pattern[i]), i + 1
    return re.compile("^" + out + "$")


def matches(rel, patterns):
    return any(glob_re(p.strip()).match(rel) for p in patterns if p.strip())


def rel_path(path):
    # The path relative to the project, with forward slashes.
    try:
        return os.path.relpath(path, project_dir()).replace(os.sep, "/") if os.path.isabs(path) else path.replace(os.sep, "/")
    except ValueError:
        return path.replace(os.sep, "/")


def pr_files():
    # The `files:` globs of the first unfinished PR, empty when the plan lists none.
    prs = todo_prs()
    found = re.search(r"(?m)^files:[ \t]*(.+)$", prs[0][1]) if prs else None
    return [g.strip() for g in found.group(1).split(",") if g.strip()] if found else []


def first_run():
    # No config file yet: the defaults apply. The ship skill tells the user once what that means, then saves them.
    try:
        files = subprocess.run(
            ["git", "-C", project_dir(), "ls-files"], capture_output=True, text=True, timeout=5
        ).stdout.split()
    except (OSError, subprocess.SubprocessError):
        files = []
    folders = len({f.split("/")[0] for f in files if "/" in f})
    return (
        f"[dotagent] first run: no .dotagent/config.json, so the defaults apply (workflow=auto) to a repo of "
        f"{len(files)} tracked files in {folders} top-level folders. The first time the ship skill runs, say in two lines: that "
        "each PR merges by itself when the review is clean and CI is green and the run goes on until every PR is merged or a stop, "
        "and that /dotagent:workflow changes it. Then ask once whether to set up first (recommended) or go on with only a TODO, "
        "and save the workflow and the setup answer with run.sh set."
    )


def log_spawn(tool_input):
    # Records one subagent spawn so a run can show what really ran. Never blocks.
    record(agent=tool_input.get("subagent_type") or "general")


def receipt():
    # `reviewer 1, Explore 2` for this session, or `none`.
    counts = {}
    for event in entries():
        if "agent" in event:
            name = str(event["agent"]).split(":")[-1]
            counts[name] = counts.get(name, 0) + 1
    return ", ".join(f"{k} {v}" for k, v in counts.items()) or "none"


def prune_runs():
    # At session start keep only the newest gate pass. Spawns and plan phases belong to the session that wrote them.
    kept = [event for event in entries() if "gate" in event][-1:]
    path = os.path.join(project_dir(), RUNS)
    try:
        if not kept:
            os.remove(path)
            return
        with open(path, "w", encoding="utf-8", newline="\n") as handle:
            for event in kept:
                handle.write(json.dumps(event) + "\n")
    except OSError:
        pass


def opt(name):
    global _settings
    _settings = _settings or load()
    return _settings[name.lower()]


def cli(args):
    # `set <key> <value>` validates and writes the config file, `show` prints it.
    if args[:1] == ["show"]:
        print(" ".join(f"{k}={v}" for k, v in load().items()))
        return
    if args[:1] == ["hooks"]:
        print(git_hooks())
        return
    if args[:1] == ["receipt"]:
        print("subagents: " + receipt())
        return
    if args[:1] == ["status"]:
        print(len(unfinished()))
        return
    if args[:1] == ["gate"] and args[1:] == ["check"]:
        print(gate_check())
        return
    if args[:1] == ["gate"] and len(args) > 2 and args[1] == "run":
        # Runs the repo gate and records the commit only when it exits 0, so a record always means the command passed.
        head = clean_head()
        if not head:
            sys.exit("gate run needs a git repo with no uncommitted change to tracked files, commit first")
        try:
            code = subprocess.run(args[2:], cwd=project_dir()).returncode
        except OSError as err:
            sys.exit(f"gate run could not start {args[2]}: {err}")
        if code != 0 or clean_head() != head:
            sys.exit(code or 1)
        record(gate=head)
        print("gate passed at " + head[:7])
        return
    if len(args) == 2 and args[0] == "phase" and args[1] in ("plan", "build", "done"):
        record(phase=args[1])
        print("phase=" + args[1])
        return
    if len(args) != 3 or args[0] != "set":
        sys.exit("usage: guard.py show | hooks | receipt | status | gate run <command>|check | set <key> <value> | phase plan|build|done")
    key, value = args[1], args[2]
    if key == "workflow":
        value = MODE_ALIASES.get(value, value)
    if key == "scale":
        sys.exit("scale was removed: the ship skill sizes each run itself, and a one sentence diff has no plan")
    if key in CHOICES and value not in CHOICES[key]:
        sys.exit(f"{key} must be one of: {', '.join(CHOICES[key])}")
    if key in ANSWERS and value not in ANSWERS[key]:
        sys.exit(f"{key} must be one of: {', '.join(ANSWERS[key])}")
    if key == "commit_types" and not TYPE_LIST.fullmatch(value):
        sys.exit("commit_types is a comma separated list of lowercase types, like feat,fix,chore")
    if key == "base_branch" and not BRANCH.fullmatch(value):
        sys.exit("base_branch is a branch name, like develop")
    if key not in CHOICES and key not in ANSWERS and key not in ("style_skills", "protected", "commit_types", "base_branch"):
        sys.exit("unknown key, use: " + ", ".join(list(CHOICES) + list(ANSWERS) + ["style_skills", "protected", "commit_types", "base_branch"]))
    path = config_path()
    try:
        with open(path, encoding="utf-8") as handle:
            raw = json.load(handle)
    except (OSError, ValueError):
        raw = {}
    raw[key] = value
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as handle:
        json.dump(raw, handle, indent=2)
        handle.write("\n")
    ensure_ignored()
    print(f"{key}={value}")


def block(reason):
    # Blocks the tool call and tells the agent what to do instead.
    print("dotagent: " + reason, file=sys.stderr)
    sys.exit(2)


def flag_values(tokens, short, long):
    # Collects the value of every `-x value`, `-xvalue`, `--long value` and `--long=value` flag.
    values = []
    for i, tok in enumerate(tokens):
        if tok == long or (short and tok == short):
            if i + 1 < len(tokens):
                values.append(tokens[i + 1])
        elif tok.startswith(long + "="):
            values.append(tok.split("=", 1)[1])
    return values


def commits_in(tokens):
    # Splits a shell command into the argument lists of each `git commit`.
    found = []
    for i in range(len(tokens) - 1):
        if tokens[i] == "git" and tokens[i + 1] == "commit":
            end = len(tokens)
            for j in range(i + 2, len(tokens)):
                if tokens[j] in ("&&", "||", ";", "|"):
                    end = j
                    break
            found.append(tokens[i + 2 : end])
    return found


def ask(reason):
    # Lets the user decide: Claude Code shows its own permission prompt. In a headless run nobody can answer, so it is a no.
    # Codex has no ask decision yet, so there the call is refused with the reason instead.
    if CLIENT == "codex":
        block(reason + " Codex cannot show a prompt: ask the user in the chat, they run the command or change the workflow.")
    print(json.dumps({"hookSpecificOutput": {"hookEventName": "PreToolUse", "permissionDecision": "ask",
                                              "permissionDecisionReason": "dotagent: " + reason}}))
    sys.exit(0)


def gate(kind):
    # Push, pull request, and merge follow the workflow mode. In ask the permission prompt is the user's yes.
    mode = opt("WORKFLOW")
    if mode == "local":
        block(f"workflow is local: nothing leaves this machine, so no {kind}. Keep the commits local and tell the user.")
    if mode == "ask":
        ask(f"workflow is ask: this {kind} needs your yes. Confirm it in the chat first, then answer this prompt yes.")


def no_label(text, where):
    # Refuses a plan label in a commit message, PR title, or merge subject.
    if LABEL.search(text):
        block(f"no plan label in {where}. Say what changed, not which task, slice, step, or milestone it was.")


def no_emoji(text, where):
    # Refuses an emoji in commit and PR text, unless the user allowed it.
    if opt("EMOJI") != "allow" and EMOJI.search(text):
        block(f"no emoji in {where}.")


def no_skip(args, where):
    # The git hooks run format, lint, and the name checks, so skipping them with --no-verify is refused.
    if "--no-verify" in args or any(re.fullmatch(r"-[a-zA-Z]*n[a-zA-Z]*", a) for a in args if where == "commit"):
        block(f"do not skip the git hooks on {where}. Fix what they report, they run format and lint before CI does.")


def check_commit(args):
    # A commit message is one conventional line, no trailer, no em dash.
    messages = flag_values(args, "-m", "--message")
    for tok in args:
        if re.fullmatch(r"-[a-zA-Z]*m", tok) and tok != "-m":
            messages += flag_values(args, tok, "--none")
    if not messages:
        return
    if len(messages) > 1:
        block("a commit message is a single line. Use one -m and put the detail in the PR.")
    msg = messages[0]
    # One line. The only body allowed is the hash list of a local squash: `- <short hash> <subject>`, one per commit.
    head, *rest = msg.split("\n")
    if "<<" in msg or any(line.strip() and not COMMIT_LINE.match(line) for line in rest):
        block("a commit message is a single line, no body and no heredoc. Only a local squash lists `- <hash> <subject>` lines.")
    if TRAILER.search(msg):
        block("no trailer in commit messages: no Co-Authored-By, Signed-off-by, or generated-by line.")
    msg = head
    if PR_NUMBER.search(msg) and not msg.lower().startswith("revert"):
        block("no (#N) in a commit message, GitHub adds the PR number when it merges.")
    if TRAILER.search(msg):
        block("no trailer in commit messages: no Co-Authored-By, Signed-off-by, or generated-by line.")
    if EM_DASH in msg and opt("EM_DASH") != "allow":
        block("no em dash in commit messages. Use a comma, period, or parentheses.")
    no_emoji(msg, "commit messages")
    no_label(msg, "commit messages")
    if not commit_pattern().match(msg):
        if opt("COMMIT_SCOPE") == "optional":
            block("commit message must look like `type: summary` or `type(scope): summary`, for example `fix: stop token reuse`.")
        block("commit message must look like `type(scope): summary`, for example `fix(auth): stop token reuse`.")


def commit_types():
    # The commit types of this repo: the saved list, or the default one.
    return "|".join(opt("COMMIT_TYPES").split(",")) if opt("COMMIT_TYPES") else TYPES


def commit_pattern():
    # `type(scope): summary`, with the scope optional when the repo saved commit_scope=optional.
    scope = rf"({SCOPE})?" if opt("COMMIT_SCOPE") == "optional" else SCOPE
    return re.compile(rf"^({commit_types()}){scope}: \S")


def title_pattern():
    return re.compile(rf"^({commit_types()})({SCOPE})?: \S")


def check_pr_create(tokens):
    # A PR title follows the commit format and no text carries an em dash.
    for title in flag_values(tokens, "-t", "--title"):
        if not title_pattern().match(title):
            block("PR title must look like `type: summary` or `type(scope): summary`.")
    for text in flag_values(tokens, "-t", "--title") + flag_values(tokens, "-b", "--body"):
        if TRAILER.search(text):
            block("no generated-by line or Co-Authored-By in PR text. Write only the change.")
    for title in flag_values(tokens, "-t", "--title"):
        if PR_NUMBER.search(title):
            block("no (#N) in a PR title, GitHub adds the PR number when it merges.")
        no_label(title, "PR titles")
    for text in flag_values(tokens, "-t", "--title") + flag_values(tokens, "-b", "--body"):
        if EM_DASH in text and opt("EM_DASH") != "allow":
            block("no em dash in PR text. Use a comma, period, or parentheses.")
        no_emoji(text, "PR text")


def check_pr_merge(tokens):
    # Merging follows the workflow mode. --admin skips the required checks, so it is refused. Another merge method than the
    # repo's merge_method asks instead of blocking. A trailer in the merge text is refused, GitHub would copy it into history.
    if "--admin" in tokens:
        block("do not merge with --admin, it skips the branch protection and the required checks.")
    method = opt("MERGE_METHOD")
    flags = {"squash": {"-s", "--squash"}, "merge": {"-m", "--merge"}, "rebase": {"-r", "--rebase"}}
    others = set().union(*(f for m, f in flags.items() if m != method))
    if others & set(tokens) or not flags[method] & set(tokens):
        ask(f"this repo merges with {method} (`merge_method`), but this command uses another method. Use --{method}, or ask the user first.")
    for text in flag_values(tokens, "-t", "--subject") + flag_values(tokens, "-b", "--body"):
        if TRAILER.search(text):
            block("no generated-by line or Co-Authored-By in the merge text, GitHub would copy it into the default branch.")
    gate("merge")


def on_bash(command):
    # Routes a Bash command to the commit, PR create, or PR merge check.
    try:
        tokens = shlex.split(command, posix=True)
    except ValueError:
        tokens = command.split()
    if phase() == "plan":
        if re.search(r"\bgit (commit|push)\b|\bgh pr (create|merge)\b", command):
            block("planning is read-only. Settle the plan with the user first, then run `phase build`.")
        if WRITE.search(command) and "TODO.md" not in command:
            block("planning is read-only. Only docs/TODO.md may change, and no shell command may write.")
    if re.search(r"\.dotagent[/\\]config\.json", command) and WRITE.search(command) and "run.sh" not in command:
        block("do not edit .dotagent/config.json from the shell. Ask the user to run /dotagent:workflow.")
    for args in commits_in(tokens):
        no_skip(args, "commit")
        check_commit(args)
    for i in range(len(tokens) - 1):
        if tokens[i] == "git" and tokens[i + 1] == "push":
            no_skip(tokens[i + 2 :], "push")
            if {"-f", "--force"} & set(tokens[i + 2 :]):
                block("do not force push. After a rebase use --force-with-lease, on your own branch only.")
            gate("push")
    for i in range(len(tokens) - 2):
        if tokens[i] == "gh" and tokens[i + 1] == "pr":
            if tokens[i + 2] == "create":
                check_pr_create(tokens[i + 3 :])
                gate("pull request")
            elif tokens[i + 2] == "merge":
                check_pr_merge(tokens[i + 3 :])
            elif tokens[i + 2] in ("review", "comment"):
                gate("review or comment")
    for i in range(len(tokens) - 1):
        # gh api writes (POST, PUT, PATCH, DELETE, or fields that make it a POST) post a review or a reply, so they follow the mode too.
        if tokens[i] == "gh" and tokens[i + 1] == "api":
            rest = tokens[i + 2 :]
            method = (flag_values(rest, "-X", "--method") or [""])[0].upper()
            fields = any(t in ("-f", "-F", "--field", "--raw-field", "--input") for t in rest)
            if method in ("POST", "PUT", "PATCH", "DELETE") or (fields and not method):
                gate("review or comment")


PATCH_PATH = re.compile(r"^\*\*\* (?:Add File|Update File|Delete File|Move to): (.+)$", re.M)


def on_patch(text):
    # Codex edits files with apply_patch: the paths sit in the patch text, and each one goes through the file rules.
    for rel in PATCH_PATH.findall(text):
        on_write({"file_path": rel.strip(), "content": text})


def on_write(tool_input):
    # The config is the user's: the agent changes it only through /dotagent:workflow.
    path = tool_input.get("file_path", "")
    if phase() == "plan" and not is_path(path, TODO):
        block("planning is read-only. Only docs/TODO.md may change until the plan is settled.")
    if is_config(path):
        block("do not edit .dotagent/config.json. Ask the user to run /dotagent:workflow.")
    rel = rel_path(path)
    if matches(rel, opt("PROTECTED").split(",")):
        block(f"{rel} is a protected path (`protected` in .dotagent/config.json). Leave it and tell the user what needs to change.")
    # While building, the lead edits only the files the plan lists for the PR, so a stray edit shows up at once.
    if phase() == "build" and not is_path(path, TODO):
        allowed = pr_files()
        if allowed and not matches(rel, allowed):
            block(
                f"{rel} is outside this PR's `files:` in docs/TODO.md ({', '.join(allowed)}). Add the path to `files:` "
                "with one line of reason in docs/TODO.md, then retry, and name it in the final report."
            )
    # Refuses an em dash in text the agent writes, unless the user allowed it.
    if opt("EM_DASH") == "allow":
        return
    text = tool_input.get("content") or tool_input.get("new_string") or ""
    if EM_DASH in text:
        block("no em dash in files. Use a comma, period, or parentheses.")


def main():
    # Dispatches on the hook event and tool name. `--client codex` comes first when the Codex hook entry runs the guard.
    global CLIENT
    args = sys.argv[1:]
    if args[:2] == ["--client", "codex"]:
        CLIENT, args = "codex", args[2:]
    if args:
        return cli(args)
    # Windows defaults stdin to the ANSI code page, which would garble an emoji before the check sees it.
    sys.stdin.reconfigure(encoding="utf-8")
    try:
        event = json.load(sys.stdin)
    except json.JSONDecodeError:
        return
    if event.get("hook_event_name") == "SessionStart":
        prune_runs()
        print(
            f"[dotagent] workflow={opt('WORKFLOW')} "
            f"style={opt('STYLE_SKILLS')}"
            # A repo flow that is not the default shows up here, so the ship skill follows it.
            + "".join(f" {tag}={opt(key)}" for tag, key, default in (
                ("merge", "MERGE_METHOD", "squash"), ("types", "COMMIT_TYPES", ""), ("scope", "COMMIT_SCOPE", "required"), ("base", "BASE_BRANCH", ""))
                if opt(key) != default)
            + (f" protected={opt('PROTECTED')}" if opt("PROTECTED") else "")
            + "".join(f" {k}={opt(k)}" for k in ANSWERS if opt(k))
        )
        if is_first_run():
            print(first_run())
        if git_hooks() == "off":
            print(
                "[dotagent] git hooks are off: .githooks exists but git does not use it, so format, lint, and name checks "
                "skip every commit and push. Tell the user, and with their yes, run `git config core.hooksPath .githooks`."
            )
        left = unfinished()
        if left:
            print(
                f"[dotagent] unfinished: {len(left)} PR(s) left in docs/TODO.md, first is {left[0]}. When the user says "
                "continue, in any wording, invoke the dotagent ship skill with no new task and carry on."
            )
        return
    tool = event.get("tool_name")
    tool_input = event.get("tool_input") or {}
    if tool == "Bash":
        on_bash(tool_input.get("command", ""))
    elif tool in ("Write", "Edit"):
        on_write(tool_input)
    elif tool == "apply_patch":
        on_patch(tool_input.get("command", ""))
    elif tool in ("Agent", "Task", "spawn_agent"):
        log_spawn(tool_input)


if __name__ == "__main__":
    main()
